# End-to-end smoke test. Usage: npm run build && npm run preview, then:
#   pip install playwright && playwright install chromium && python scripts/e2e_check.py
from playwright.sync_api import sync_playwright, expect
import os
B=os.environ.get("BASE_URL", "http://localhost:4173")
results=[]
def check(name, cond):
    results.append(("PASS" if cond else "FAIL")+"  "+name)
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={"width":1280,"height":900})
    pg = ctx.new_page()
    errs=[]
    pg.on("console", lambda m: errs.append(m.text) if m.type=="error" else None)
    pg.on("pageerror", lambda e: errs.append(str(e)))

    # --- Navigation
    pg.goto(B+"/", wait_until="networkidle")
    pg.click(".navbar__desktop >> text=Events"); pg.wait_for_url("**/events")
    check("nav: Events link routes to /events", pg.url.endswith("/events"))
    check("nav: Events link active", pg.locator(".navbar__link.is-active").inner_text()=="Events")
    pg.click(".navbar__desktop >> text=About"); pg.wait_for_timeout(800)
    check("nav: About scrolls to #about on home", pg.url.endswith("/#about") and pg.evaluate("Math.abs(document.getElementById('about').getBoundingClientRect().top) < 200"))
    pg.click(".navbar__desktop >> text=Register"); pg.wait_for_url("**/register")
    check("nav: Register CTA routes", "/register" in pg.url)

    # --- Search & filters
    pg.goto(B+"/events", wait_until="networkidle")
    total = pg.locator(".event-card").count()
    check(f"events: renders >=6 cards ({total})", total>=6)
    pg.fill("#event-search-input","tamil"); pg.wait_for_timeout(400)
    n = pg.locator(".event-card").count()
    check(f"search 'tamil' narrows ({n})", 0<n<total)
    check("search syncs ?q= to URL", "q=tamil" in pg.url)
    pg.click("role=radio[name=/^Drama/]"); pg.wait_for_timeout(300)
    titles = pg.locator(".event-card__title").all_inner_texts()
    check(f"search + category combine -> {titles}", titles==["Rangmanch"])
    check("category in URL", "cat=Drama" in pg.url)
    pg.fill("#event-search-input","zzqx"); pg.wait_for_timeout(400)
    check("empty state shown", pg.locator(".empty-state").is_visible() and "No events match" in pg.locator(".empty-state").inner_text())
    pg.click(".empty-state >> text=Reset search")
    pg.wait_for_timeout(400)
    check("reset restores all events", pg.locator(".event-card").count()==total and pg.input_value("#event-search-input")=="")
    check("reset focuses search box", pg.evaluate("document.activeElement.id")=="event-search-input")
    # keyboard radio nav
    pg.focus("role=radio[name=/^All/]"); pg.keyboard.press("ArrowRight"); pg.wait_for_timeout(200)
    check("arrow key moves filter to Dance", pg.locator("role=radio[checked=true]").inner_text().startswith("Dance"))
    pg.keyboard.press("Home")

    # --- Modal
    pg.goto(B+"/events", wait_until="networkidle")
    btn = pg.locator(".event-card", has_text="Skyward").locator(".event-card__cta")
    btn.click(); pg.wait_for_timeout(300)
    check("modal opens with correct event", pg.locator("#event-modal-title").inner_text()=="Skyward")
    check("modal ?event in URL", "event=skyward" in pg.url)
    check("focus moved into modal (close button)", pg.evaluate("document.activeElement.classList.contains('modal__close')"))
    for _ in range(12): pg.keyboard.press("Tab")
    check("focus trapped inside dialog", pg.evaluate("!!document.activeElement.closest('.modal__dialog')"))
    check("body scroll locked", pg.evaluate("document.body.style.overflow")=="hidden")
    pg.keyboard.press("Escape"); pg.wait_for_timeout(300)
    check("Escape closes modal", pg.locator(".modal").count()==0 and "event=" not in pg.url)
    check("focus restored to trigger", pg.evaluate("document.activeElement.textContent.includes('View details')"))
    btn.click(); pg.wait_for_timeout(200); pg.click(".modal__close"); pg.wait_for_timeout(200)
    check("close button closes", pg.locator(".modal").count()==0)
    btn.click(); pg.wait_for_timeout(200); pg.mouse.click(5,5); pg.wait_for_timeout(200)
    check("backdrop click closes", pg.locator(".modal").count()==0)
    btn.click(); pg.wait_for_timeout(200); pg.go_back(); pg.wait_for_timeout(300)
    check("browser Back closes modal", pg.locator(".modal").count()==0)
    pg.goto(B+"/events?event=not-a-real-event", wait_until="networkidle")
    check("unknown event id -> not-found state", "Event not found" in pg.locator(".modal").inner_text())
    pg.goto(B+"/events?event=rangmanch", wait_until="networkidle")
    pg.click("text=Register for Rangmanch"); pg.wait_for_url("**/register?event=rangmanch")
    check("modal register CTA preselects event", pg.input_value("#reg-eventId")=="rangmanch")

    # --- Registration
    pg.goto(B+"/register", wait_until="networkidle")
    pg.click("button[type=submit]"); pg.wait_for_timeout(200)
    check("empty submit shows 6 inline errors", pg.locator(".field__error").count()==6)
    check("error summary shown", pg.locator(".reg-form__summary").is_visible())
    check("focus moves to first invalid field", pg.evaluate("document.activeElement.id")=="reg-fullName")
    check("aria-invalid set", pg.get_attribute("#reg-email","aria-invalid")=="true")
    pg.fill("#reg-fullName","Ananya Iyer"); pg.fill("#reg-email","bad@"); pg.fill("#reg-phone","12345")
    pg.wait_for_timeout(100)
    check("bad email message", "valid email" in pg.locator("#reg-email-error").inner_text())
    check("bad phone message", "10-digit" in pg.locator("#reg-phone-error").inner_text())
    check("name error clears live", pg.locator("#reg-fullName-error").count()==0)
    pg.fill("#reg-email","ananya@college.edu"); pg.fill("#reg-phone","+91 98765 43210")
    pg.fill("#reg-college","SRM Institute of Science and Technology")
    pg.select_option("#reg-eventId","skyward")
    check("selected event preview appears", "Skyward" in pg.locator(".reg-form__preview").inner_text())
    pg.check("#reg-consent")
    pg.evaluate("localStorage.clear()")
    pg.click("button[type=submit]")
    pg.wait_for_timeout(100)
    check("loading state: button busy & fieldset disabled", pg.get_attribute("button[type=submit]","aria-busy")=="true" and pg.evaluate("document.querySelector('fieldset').disabled"))
    pg.locator("button[type=submit]").click(force=True)  # double-click attempt
    pg.wait_for_selector(".reg-success", timeout=4000)
    check("success state with DEMO reference", "DEMO-" in pg.locator(".reg-success__ticket").inner_text())
    check("only one record stored (duplicate prevention)", pg.evaluate("JSON.parse(localStorage.getItem('milan-demo-registrations')).length")==1)
    # duplicate
    pg.click("text=Register for another event")
    pg.fill("#reg-fullName","Ananya Iyer"); pg.fill("#reg-email","ananya@college.edu"); pg.fill("#reg-phone","9876543210")
    pg.fill("#reg-college","SRM IST"); pg.select_option("#reg-eventId","skyward"); pg.check("#reg-consent")
    pg.click("button[type=submit]"); pg.wait_for_selector(".reg-form__summary", timeout=4000)
    check("duplicate registration rejected", "already registered" in pg.locator(".reg-form__summary").inner_text())
    pg.fill("#reg-email","x@fail.test"); pg.click("button[type=submit]"); pg.wait_for_timeout(1700)
    check("server error state shown", "could not be reached" in pg.locator(".reg-form__summary").inner_text())

    # --- 404
    pg.goto(B+"/nope", wait_until="networkidle")
    check("404 page renders", "Wrong turn" in pg.inner_text("h1"))
    check(f"no console errors {errs}", not errs)
    ctx.close()

    # --- Mobile menu
    ctx = b.new_context(viewport={"width":375,"height":812}); pg = ctx.new_page()
    pg.goto(B+"/", wait_until="networkidle")
    pg.click(".navbar__toggle"); pg.wait_for_timeout(300)
    check("mobile menu opens", pg.locator("#mobile-menu").is_visible() and pg.get_attribute(".navbar__toggle","aria-expanded")=="true")
    pg.keyboard.press("Escape"); pg.wait_for_timeout(200)
    check("Escape closes mobile menu", not pg.locator("#mobile-menu").is_visible())
    pg.click(".navbar__toggle"); pg.click(".mobile-menu >> text=Events"); pg.wait_for_url("**/events"); pg.wait_for_timeout(200)
    check("mobile link navigates and closes menu", not pg.locator("#mobile-menu").is_visible())
    pg.locator(".event-card__cta").first.click(); pg.wait_for_timeout(300)
    box = pg.locator(".modal__dialog").bounding_box()
    check(f"mobile modal is full-width sheet {box['width']}", box["width"]>=374)
    
    ctx.close(); b.close()
print("\n".join(results))
print(sum(r.startswith("PASS") for r in results), "/", len(results))
